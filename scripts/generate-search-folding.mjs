import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { format, resolveConfig } from 'prettier';

export const unicodeVersion = '17.0.0';
export const sourceFile = new URL(`../vendor/unicode/${unicodeVersion}/CaseFolding.txt`, import.meta.url);
export const outputFile = new URL('../src/unicode-folding-data.js', import.meta.url);

export const parseCaseFoldings = source => {
    if (!source.startsWith(`# CaseFolding-${unicodeVersion}.txt`)) throw new Error('Unexpected Unicode data version');
    const mappings = {};
    for (const line of source.split('\n')) {
        const [code, status, mapping] = line
            .split('#')[0]
            .split(';')
            .map(value => value.trim());
        if (!['C', 'F'].includes(status)) continue;
        const character = String.fromCodePoint(parseInt(code, 16));
        if (Object.hasOwn(mappings, character)) throw new Error('Duplicate full case folding');
        mappings[character] = String.fromCodePoint(...mapping.split(' ').map(value => parseInt(value, 16)));
    }
    return mappings;
};

export const renderCaseFoldings = async source => {
    const config = await resolveConfig(fileURLToPath(outputFile));
    const license = await readFile(new URL('../vendor/unicode/LICENSE.txt', import.meta.url), 'utf8');
    return format(
        `/*\n${license.trim()}\n*/\n` +
            `// Generated by scripts/generate-search-folding.mjs from Unicode ${unicodeVersion} CaseFolding.txt.\n` +
            '// Full default folding (C + F), without locale-specific Turkic overrides.\n' +
            '// Unicode License V3: vendor/unicode/LICENSE.txt.\n' +
            `export const caseFoldings = Object.freeze(${JSON.stringify(parseCaseFoldings(source))});\n`,
        { ...config, filepath: fileURLToPath(outputFile) }
    );
};

if (process.argv[1] === fileURLToPath(import.meta.url)) {
    const option = process.argv[2] || '--check';
    if (!['--check', '--write'].includes(option) || process.argv.length > 3) throw new Error('Use --check or --write');
    const content = await renderCaseFoldings(await readFile(sourceFile, 'utf8'));
    if (option === '--write') await writeFile(outputFile, content);
    else if (content !== (await readFile(outputFile, 'utf8')))
        throw new Error('Run node scripts/generate-search-folding.mjs --write');
}
